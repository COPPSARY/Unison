//! tauri-specta builder: the single list of commands, events and extra types exposed to React.
//! `src/lib/bindings.ts` is regenerated from this on every debug run and by `cargo test`.
// Export helpers run only in debug builds and tests.
#![cfg_attr(not(debug_assertions), allow(dead_code))]

use specta_typescript::Typescript;
use tauri_specta::{collect_commands, collect_events, Builder};

use crate::commands;
use crate::core::playback::engine::SourceStatus;
use crate::core::playback::player::PlayerSnapshot;
use crate::core::playback::youtube::YoutubeCommand;
use crate::core::sync::{SyncFinished, SyncProgress};
use crate::error::AppError;
use crate::model::{Account, Playlist, Signal, Track};

/// Path of the generated file, relative to `src-tauri/`.
pub const BINDINGS_PATH: &str = "../src/lib/bindings.ts";

const HEADER: &str = "// GENERATED by tauri-specta from src-tauri/src/bindings.rs. Do not edit by hand.\n/* eslint-disable */\n// @ts-nocheck";

pub fn builder() -> Builder<tauri::Wry> {
    Builder::<tauri::Wry>::new()
        .commands(collect_commands![
            commands::app::app_info,
            commands::settings::settings_get,
            commands::settings::settings_set,
            commands::accounts::accounts_list,
            commands::accounts::spotify_set_client_id,
            commands::accounts::spotify_has_client_id,
            commands::accounts::spotify_redirect_uris,
            commands::accounts::spotify_open_dashboard,
            commands::accounts::account_connect,
            commands::accounts::account_cancel_connect,
            commands::sync::sync_now,
            commands::sync::sync_cancel,
            commands::library::library_liked,
            commands::library::library_liked_stats,
            commands::library::library_albums,
            commands::library::library_artists,
            commands::library::playlists_list,
            commands::playlists::playlist_get,
            commands::playlists::playlist_tracks,
            commands::playlists::playlist_open_external,
            commands::youtube::youtube_test_playback,
            commands::youtube::youtube_test_report,
            commands::youtube::youtube_player_report,
            commands::youtube::youtube_host_ready,
            commands::player::spotify_capabilities,
            commands::player::player_outputs,
            commands::player::player_set_output,
            commands::player::player_test_sound,
        ])
        .events(collect_events![SyncProgress, SyncFinished, YoutubeCommand])
        .typ::<AppError>()
        .typ::<Account>()
        .typ::<Track>()
        .typ::<Playlist>()
        .typ::<Signal>()
        .typ::<SourceStatus>()
        .typ::<PlayerSnapshot>()
        // Unix-second timestamps fit comfortably in a JS number.
        .dangerously_cast_bigints_to_number()
}

/// Writes the TypeScript bindings.
pub fn export(builder: &Builder<tauri::Wry>, path: &str) -> Result<(), String> {
    builder
        .export(Typescript::default().header(HEADER), path)
        .map_err(|e| e.to_string())
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Keeps the committed bindings in sync; CI fails if this changes the file.
    #[test]
    fn export_bindings() {
        let path = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join(BINDINGS_PATH);
        export(&builder(), path.to_str().unwrap()).unwrap();
        let ts = std::fs::read_to_string(&path).unwrap();
        assert!(ts.contains("appInfo"), "{ts}");
        assert!(ts.contains("AppError"), "{ts}");
        assert!(ts.contains("settingsSet"), "{ts}");
        assert!(ts.contains("export type Track"), "{ts}");
        // Guard against tauri-specta emitting unbound generics in command signatures.
        assert!(!ts.contains(r#"<T>>(""#), "unbound generic in bindings");
    }
}
